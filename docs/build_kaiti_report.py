def strip_runs(p_el):
    for r in p_el.findall(qn("w:r")):
        p_el.remove(r)


def fill_cell(cell, blocks, spacing=1.5, indent_pt=21, fig_width_cm=12.5):
    """
    用 blocks 替换单元格内容，沿用该单元格首段的段落格式。

    fig_width_cm 依据实测：正文内容单元格宽 13.14 cm（合并单元格），
    留出单元格内边距后按 12.5 cm 插图；三张图均按 700 px 画布设计，
    缩放到 12.5 cm 时图内文字约 7.6 pt，可以看清。
    """
    tc = cell._tc
    tpl = copy.deepcopy(cell.paragraphs[0]._element)   # 保留 pPr 作为格式模板
    for p in list(cell.paragraphs):
        tc.remove(p._element)

    for kind, payload in blocks:
        el = copy.deepcopy(tpl)
        strip_runs(el)
        tc.append(el)
        para = Paragraph(el, cell)
        pf = para.paragraph_format

        if kind == "fig":
            pf.first_line_indent = None
            pf.line_spacing = 1.0
            para.alignment = WD_ALIGN_PARAGRAPH.CENTER
            para.add_run().add_picture(str(HERE / payload), width=Cm(fig_width_cm))
            continue

        pf.line_spacing = spacing
        run = para.add_run(payload)
        if kind in ("h1", "h2"):
            pf.first_line_indent = None
            run.bold = True
        elif kind == "ref":
            pf.first_line_indent = None
            run.font.size = Pt(10.5)
        else:
            pf.first_line_indent = Pt(indent_pt)


def fill_cover_value(para, value):
    """把封面字段的空白替换成实际值，保留原有下划线等字符格式。"""
    if not para.runs:
        return
    rest = list(para.runs[1:])
    if not rest:
        para.runs[0].text = para.runs[0].text.rstrip() + " " + value
        return
    carrier = max(rest, key=lambda r: len(r.text))
    for r in rest:
        if r is not carrier:
            r.text = ""
    carrier.text = " " + value


# ============================================================ 主流程
def main() -> int:
    if not TEMPLATE.exists():
        print(f"找不到模板：{TEMPLATE}")
        return 2

    shutil.copyfile(TEMPLATE, OUTPUT)
    doc = Document(str(OUTPUT))

    # ---- 封面 ----
    for p in doc.paragraphs:
        t = p.text.replace(" ", "")
        if t.startswith("课题名称："):
            fill_cover_value(p, TITLE_COVER)
        elif t.startswith("专业名称："):
            fill_cover_value(p, MAJOR)

    # ---- 正文表格 ----
    table = doc.tables[0]

    # 模板的 tblLayout 是 autofit：正文一长，列宽会被内容撑开，整张表冲出页面右边界。
    # 模板本身已经为每一列写好了 gridCol 宽度（合计 15.85 cm），改成 fixed 即为作者的原意。
    tblPr = table._tbl.find(qn("w:tblPr"))
    layout = tblPr.find(qn("w:tblLayout"))
    if layout is None:
        layout = tblPr.makeelement(qn("w:tblLayout"), {})
        tblPr.append(layout)
    layout.set(qn("w:type"), "fixed")

    # 表头两行：专业 / 所在单位（姓名、学号、指导教师留给本人填写）
    row0 = table.rows[0]
    row1 = table.rows[1]
    cells0 = [c for c in row0.cells]
    cells1 = [c for c in row1.cells]
    if len(cells0) >= 6:
        fill_cell(cells0[5], [("body_plain", MAJOR)])
    if len(cells1) >= 6:
        fill_cell(cells1[5], [("body_plain", UNIT)])

    # 五个内容单元格
    targets = [
        (4, CONTENT_MEANING, 1.5),
        (5, CONTENT_LITERATURE, 1.5),
        (6, CONTENT_RESEARCH, 1.5),
        (7, CONTENT_PLAN, 1.5),
        (8, CONTENT_FEATURE, 1.5),
    ]
    for ri, blocks, spacing in targets:
        row = table.rows[ri]
        content_cell = None
        seen = set()
        for c in row.cells:
            if id(c._tc) in seen:
                continue
            seen.add(id(c._tc))
            if len(c.text.strip()) > 40:      # 内容列文字最多
                content_cell = c
        if content_cell is None:
            content_cell = row.cells[-1]
        # body_plain 也需要首行缩进之外的普通处理
        norm = []
        for kind, text in blocks:
            norm.append(("body" if kind == "body_plain" else kind, text))
        fill_cell(content_cell, norm, spacing=spacing)

    # 第 5 行的行标题里带有模板批注，清成纯标题
    label_cell = None
    for c in table.rows[5].cells:
        if "文献综述" in c.text:
            label_cell = c
            break
    if label_cell is not None:
        paras = label_cell.paragraphs
        for p in paras[1:]:
            p._element.getparent().remove(p._element)
        first = paras[0]
        for r in list(first.runs)[1:]:
            r._element.getparent().remove(r._element)
        if first.runs:
            first.runs[0].text = "文献综述"

    doc.save(str(OUTPUT))

    # ---- 统计学生撰写字数 ----
    body_text = "".join(
        t for blocks in (CONTENT_MEANING, CONTENT_LITERATURE, CONTENT_RESEARCH,
                         CONTENT_PLAN, CONTENT_FEATURE)
        for kind, t in blocks if kind not in ("fig",))
    zh = len(re.findall(r"[\u4e00-\u9fff]", body_text))
    print(f"已生成：{OUTPUT}")
    print(f"正文字数（中文字符）：{zh}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
